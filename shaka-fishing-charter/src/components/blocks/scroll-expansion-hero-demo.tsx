'use client';

import { useState, useEffect } from 'react';
import ScrollExpandMedia from '@/components/blocks/scroll-expansion-hero';

interface MediaAbout {
  overview: string;
  conclusion: string;
}

interface MediaContent {
  src: string;
  poster?: string;
  background: string;
  title: string;
  date: string;
  scrollToExpand: string;
  about: MediaAbout;
}

interface MediaContentCollection {
  [key: string]: MediaContent;
}

// Real Shaka Fishing Charter assets — aerial footage/photo of the Maui
// coastline, transcoded to /public/media for broad browser support.
const sampleMediaContent: MediaContentCollection = {
  video: {
    src: '/media/maui-coastline.mp4',
    poster: '/media/maui-coastline-poster.jpg',
    background: '/media/maui-coastline.jpg',
    title: 'Chase Blue Water',
    date: 'Lahaina, Maui',
    scrollToExpand: 'Scroll to Expand',
    about: {
      overview:
        "This is Maui's west side — the drop-offs, current lines, and open water Shaka Fishing Charter & Tours runs every charter through. Scroll back up to reset the shot, or keep going to see the day ahead.",
      conclusion:
        'Half-day, full-day, or the full-day cookout experience — every charter departs Lahaina Harbor chasing marlin, mahi-mahi, ono, and ahi in water like this.',
    },
  },
  image: {
    src: '/media/maui-coastline.jpg',
    background: '/media/maui-coastline.jpg',
    title: "Maui's West Side",
    date: 'Lahaina Harbor',
    scrollToExpand: 'Scroll to Expand',
    about: {
      overview:
        'The waters between Lahaina and Lāna\'i, shot from above — this is the grounds Shaka Fishing Charter & Tours fishes year-round.',
      conclusion:
        'Ready to see it from the boat instead of the air? Book a charter and find out firsthand.',
    },
  },
};

const MediaContent = ({ mediaType }: { mediaType: 'video' | 'image' }) => {
  const currentMedia = sampleMediaContent[mediaType];

  return (
    <div className='max-w-4xl mx-auto'>
      <h2 className='text-3xl font-bold mb-6 text-black dark:text-white'>
        About This Component
      </h2>
      <p className='text-lg mb-8 text-black dark:text-white'>
        {currentMedia.about.overview}
      </p>

      <p className='text-lg mb-8 text-black dark:text-white'>
        {currentMedia.about.conclusion}
      </p>
    </div>
  );
};

export const VideoExpansionTextBlend = () => {
  const mediaType = 'video';
  const currentMedia = sampleMediaContent[mediaType];

  useEffect(() => {
    window.scrollTo(0, 0);

    const resetEvent = new Event('resetSection');
    window.dispatchEvent(resetEvent);
  }, []);

  return (
    <div className='min-h-screen'>
      <ScrollExpandMedia
        mediaType={mediaType}
        mediaSrc={currentMedia.src}
        posterSrc={currentMedia.poster}
        bgImageSrc={currentMedia.background}
        title={currentMedia.title}
        date={currentMedia.date}
        scrollToExpand={currentMedia.scrollToExpand}
        textBlend
      >
        <MediaContent mediaType={mediaType} />
      </ScrollExpandMedia>
    </div>
  );
};

